test('production HTTPS origin, secure cookies and proxy-aware authentication', async () => {
  const dir=mkdtempSync(path.join(os.tmpdir(),'study-https-test-'));
  const db=openDatabase(path.join(dir,'test.sqlite'));
  const setupFile=path.join(dir,'setup-code.txt');
  const previousOrigin=process.env.APP_ORIGIN, previousEnvironment=process.env.NODE_ENV;
  process.env.APP_ORIGIN='https://studytimer.snlynnoo.dev';
  process.env.NODE_ENV='production';
  db.prepare('INSERT INTO users (id,email,name,role,created_at) VALUES (?,?,?,?,?)').run('owner','owner@example.com','Owner','admin',new Date().toISOString());
  const app=express(); app.set('trust proxy',1); app.use(express.json()); app.use('/api',createApi(db,setupFile));
  const server=app.listen(0,'127.0.0.1'); await once(server,'listening');
  const base=`http://127.0.0.1:${(server.address() as any).port}/api`;
  const headers={'Content-Type':'application/json',Origin:process.env.APP_ORIGIN,'X-Forwarded-Proto':'https'};
  try {
    const rejected=await fetch(base+'/auth/setup',{method:'POST',headers:{...headers,Origin:'https://malicious.example'},body:JSON.stringify({code:readFileSync(setupFile,'utf8').trim(),password:'OwnerPassword123'})});
    assert.equal(rejected.status,403);
    const setup=await fetch(base+'/auth/setup',{method:'POST',headers,body:JSON.stringify({code:readFileSync(setupFile,'utf8').trim(),password:'OwnerPassword123'})});
    assert.equal(setup.status,200);
    const cookie=setup.headers.get('set-cookie')!;
    assert.match(cookie,/; Secure/); assert.match(cookie,/HttpOnly/);
    const logout=await fetch(base+'/auth/logout',{method:'POST',headers:{...headers,Cookie:cookie.split(';')[0]},body:'{}'});
    assert.equal(logout.status,200); assert.match(logout.headers.get('set-cookie')!,/; Secure/);
    const login=await fetch(base+'/auth/login',{method:'POST',headers,body:JSON.stringify({email:'owner@example.com',password:'OwnerPassword123'})});
    assert.equal(login.status,200); assert.match(login.headers.get('set-cookie')!,/; Secure/);
  } finally {
    await new Promise<void>(resolve=>server.close(()=>resolve())); db.close(); rmSync(dir,{recursive:true,force:true});
    if(previousOrigin===undefined)delete process.env.APP_ORIGIN;else process.env.APP_ORIGIN=previousOrigin;
    if(previousEnvironment===undefined)delete process.env.NODE_ENV;else process.env.NODE_ENV=previousEnvironment;
  }
});

test('local authentication, task CRUD, date validation, account isolation and persistence', async () => {
  const dir=mkdtempSync(path.join(os.tmpdir(),'study-timer-test-'));
  const filename=path.join(dir,'test.sqlite'), setupFile=path.join(dir,'setup-code.txt');
  let db=openDatabase(filename);
  db.prepare('INSERT INTO users (id,email,name,role,created_at) VALUES (?,?,?,?,?)').run('owner','owner@example.com','Owner','admin',new Date().toISOString());
  const app=express(); app.use(express.json()); app.use('/api',createApi(db,setupFile));
  const server=app.listen(0,'127.0.0.1'); await once(server,'listening');
  const port=(server.address() as any).port;
  const base=`http://127.0.0.1:${port}/api`;
  const call=async (url: string, method='GET', body?: any, cookie?: string, origin?: string) => {
    const response=await fetch(base+url,{method,headers:{'Content-Type':'application/json',...(cookie?{cookie}:{}),...(origin?{origin}:{})},body:body===undefined?undefined:JSON.stringify(body)});
    return {status:response.status,data:await response.json(),cookie:response.headers.get('set-cookie')?.split(';')[0]};
  };
  try {
    assert.equal((await call('/users')).status,401);
    assert.equal((await call('/auth/setup')).data.required,true);
    assert.equal((await call('/auth/setup','POST',{code:'wrong',password:'OwnerPassword123'})).status,403);
    const setup=await call('/auth/setup','POST',{code:readFileSync(setupFile,'utf8').trim(),password:'OwnerPassword123'});
    assert.equal(setup.status,200); assert.ok(setup.cookie); assert.equal(existsSync(setupFile),false);
    const admin=setup.cookie!;
    assert.equal((await call('/auth/setup','POST',{})).status,409);
    assert.equal((await call('/auth/login','POST',{email:'owner@example.com',password:'wrong'})).status,401);
    assert.equal((await call('/users','POST',{name:'Member',email:'member@example.com',password:'short'},admin)).status,400);
    const created=await call('/users','POST',{name:'Member',email:'member@example.com',password:'MemberPassword123'},admin);
    assert.equal(created.status,201); assert.equal(created.data.role,'user'); assert.ok(!('password_hash' in created.data));
    const memberId=created.data.id;
    assert.equal((await call('/users','POST',{name:'Duplicate',email:'MEMBER@example.com',password:'MemberPassword123'},admin)).status,409);
    const login=await call('/auth/login','POST',{email:'member@example.com',password:'MemberPassword123'});
    assert.equal(login.status,200); const member=login.cookie!;
    assert.equal((await call('/users','GET',undefined,member)).status,403);
    assert.equal((await call(`/users/owner/password`,'POST',{password:'ForgedPassword123'},member)).status,403);
    assert.equal((await call('/users','POST',{email:'cross@example.com',password:'Password1234',name:'Cross'},admin,'https://malicious.example')).status,403);
    const session={date:'2026-11-22',start_time:'10:00',end_time:'10:25',duration:25,main_task:'Test',topic:'Isolation',user_id:'owner'};
    const saved=await call('/sessions','POST',session,member); assert.equal(saved.status,201);
    assert.equal((await call('/sessions','GET',undefined,admin)).data.length,0);
    assert.equal((await call(`/sessions/${saved.data.id}`,'PATCH',{topic:'Hijacked'},admin)).status,404);
    assert.equal((await call(`/sessions/${saved.data.id}`,'DELETE',{},admin)).status,404);
    assert.equal((await call(`/sessions/${saved.data.id}`,'PATCH',{topic:'Updated'},member)).status,200);
    const memberRows=(await call('/sessions','GET',undefined,member)).data;
    assert.equal(memberRows[0].user_id,memberId);assert.equal(memberRows[0].topic,'Updated');
    assert.equal((await call('/todos?from=2026-11-01&to=2026-11-30')).status,401);
    const task=await call('/todos','POST',{title:'Plan next chapter',date:'2026-11-22',notes:'Read pages 1–10',user_id:'owner'},member);
    assert.equal(task.status,201);assert.equal(task.data.user_id,memberId);assert.equal(task.data.completed,false);
    assert.equal((await call('/todos?from=2026-11-01&to=2026-11-30','GET',undefined,admin)).data.length,0);
    assert.equal((await call(`/todos/${task.data.id}`,'PATCH',{title:'Hijacked'},admin)).status,404);
    assert.equal((await call(`/todos/${task.data.id}`,'DELETE',{},admin)).status,404);
    for(const date of ['2026-02-30','not-a-date','2026-11-00']) assert.equal((await call('/todos','POST',{title:'Invalid date',date},member)).status,400);
    assert.equal((await call('/todos','POST',{title:'   ',date:'2026-11-22'},member)).status,400);
    assert.equal((await call('/todos','POST',{title:'Invalid status',date:'2026-11-22',completed:'true'},member)).status,400);
    assert.equal((await call('/todos?from=2026-12-01&to=2026-11-01','GET',undefined,member)).status,400);
    assert.equal((await call('/todos?from=bad&to=2026-11-30','GET',undefined,member)).status,400);
    const moved=await call(`/todos/${task.data.id}`,'PATCH',{date:'2026-11-23',title:'Revised task',completed:true},member);
    assert.equal(moved.status,200);assert.equal(moved.data.completed,true);assert.equal(moved.data.notes,'Read pages 1–10');
    assert.equal((await call('/todos?from=2026-11-22&to=2026-11-22','GET',undefined,member)).data.length,0);
    assert.equal((await call('/todos?from=2026-11-23&to=2026-11-23','GET',undefined,member)).data[0].title,'Revised task');
    const disposable=await call('/todos','POST',{title:'Remove me',date:'2026-11-23'},member);
    assert.equal((await call(`/todos/${disposable.data.id}`,'DELETE',{},member)).status,200);
    assert.equal((await call(`/todos/${disposable.data.id}`,'DELETE',{},member)).status,404);
    // Timer retries use a stable ID, and repeated break checkpoints cannot double-count time.
    const focusId='11111111-2222-4333-8444-555555555555';
    const timed={...session,id:focusId,owner_id:memberId};
    assert.equal((await call('/sessions','POST',timed,member)).status,201);
    assert.equal((await call('/sessions','POST',timed,member)).status,200);
    assert.equal((await call('/sessions','POST',{...timed,main_task:'Conflicting task'},member)).status,409);
    assert.equal((await call('/sessions','POST',{...timed,owner_id:'owner'},member)).status,403);
    assert.equal((await call(`/sessions/${focusId}/break`,'PUT',{seconds:125},admin)).status,404);
    assert.equal((await call(`/sessions/${focusId}/break`,'PUT',{seconds:125,owner_id:memberId},member)).data.break_seconds,125);
    assert.equal((await call(`/sessions/${focusId}/break`,'PUT',{seconds:125},member)).data.break_seconds,125);
    assert.equal((await call(`/sessions/${focusId}/break`,'PUT',{seconds:15},member)).data.break_seconds,125);
    assert.equal((await call(`/sessions/${focusId}/break`,'PUT',{seconds:180},member)).data.break_seconds,180);
    assert.equal((await call(`/sessions/${focusId}/break`,'PUT',{seconds:-1},member)).status,400);
    assert.equal((await call(`/sessions/${focusId}/break`,'PUT',{seconds:1.5},member)).status,400);
    assert.equal((await call(`/sessions/${focusId}/break`,'PUT',{seconds:10,owner_id:'owner'},member)).status,403);
    const storedSessions=(await call('/sessions','GET',undefined,member)).data;
    assert.equal(storedSessions.length,2);
    assert.equal(storedSessions.find((row:any)=>row.id===saved.data.id).break_seconds,null);
    assert.equal(storedSessions.find((row:any)=>row.id===focusId).break_seconds,180);
    const settings={timer:{work:25,shortBreak:5,longBreak:15,darkModeWhenRunning:false},theme:{work:'bg-indigo-900',shortBreak:'bg-yellow-400',longBreak:'bg-green-500'},sound:{enabled:true,type:'https://example.com/sound.mp3',volume:.5,repeatCount:1}};
    assert.equal((await call('/settings','PUT',settings,member)).status,200);
    assert.deepEqual((await call('/settings','GET',undefined,member)).data,settings);
    assert.equal((await call('/settings','GET',undefined,admin)).data,null);
    assert.equal((await call(`/users/${memberId}/password`,'POST',{password:'ReplacementPassword123'},admin)).status,200);
    assert.equal((await call('/sessions','GET',undefined,member)).status,401);
    assert.equal((await call('/auth/login','POST',{email:'member@example.com',password:'MemberPassword123'})).status,401);
    const newLogin=await call('/auth/login','POST',{email:'member@example.com',password:'ReplacementPassword123'});assert.equal(newLogin.status,200);
    assert.equal((await call('/auth/logout','POST',{},newLogin.cookie!)).status,200);
    assert.equal((await call('/sessions','GET',undefined,newLogin.cookie!)).status,401);
    assert.equal((await call('/users','GET',undefined,admin)).data.some((u:any)=>'password_hash' in u),false);
    const hash=db.prepare('SELECT password_hash FROM users WHERE id=?').get(memberId)!.password_hash as string;
    assert.ok(hash.startsWith('scrypt:'));assert.ok(!hash.includes('ReplacementPassword123'));
    db.close();db=openDatabase(filename);
    assert.equal(db.prepare('SELECT count(*) AS n FROM sessions').get()!.n,2);
    assert.equal(db.prepare('SELECT break_seconds FROM sessions WHERE id=?').get(focusId)!.break_seconds,180);
    assert.equal(db.prepare('SELECT count(*) AS n FROM users').get()!.n,2);
    assert.equal(db.prepare('SELECT count(*) AS n FROM user_settings').get()!.n,1);
    assert.equal(db.prepare('SELECT count(*) AS n FROM todos').get()!.n,1);
    assert.equal(db.prepare('SELECT title,completed FROM todos').get()!.title,'Revised task');
  } finally {await new Promise<void>(resolve=>server.close(()=>resolve()));db.close();rmSync(dir,{recursive:true,force:true});}
});
